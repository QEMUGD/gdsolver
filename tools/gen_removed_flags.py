#!/usr/bin/env python
"""Generate the table of removed leveldp switches from its text source.

    python tools/gen_removed_flags.py            # rewrite dp/src/dp/removed_flags.gen.hpp
    python tools/gen_removed_flags.py --check    # exit 1 if it is stale

dp/removed_flags.txt is the source: one spelling per line with the commit that removed it, the commit the
refusal names and a one-phrase reason (its header says how each is read). cliMain refuses a caller that still
passes one of them by name, from the table this writes; leveldp does not read the text at run time (the
solver also runs inside the mod, where there is no dp/ folder to find it in).

Like tools/gen_effective_cfg.py, the generated header is committed, and tools/test_removed_flags.py fails
while it is behind the text. Run this after adding a line.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "dp" / "removed_flags.txt"
OUT = ROOT / "dp" / "src" / "dp" / "removed_flags.gen.hpp"

SPELLING = re.compile(r"--[a-z0-9][a-z0-9-]*=?")
SHA = re.compile(r"[0-9a-f]{7,40}")


class SourceError(Exception):
    pass


def parse(text: str) -> list[tuple[str, str, str, str]]:
    """The (spelling, removed-in, since, reason) of every line, in the file's order."""
    rows: list[tuple[str, str, str, str]] = []
    seen: dict[str, int] = {}
    for no, raw in enumerate(text.split("\n"), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 3)
        if len(parts) < 4:
            raise SourceError(f"line {no}: want '<spelling> <removed-in> <since> <reason>', got {line!r}")
        spelling, removed, since, reason = parts
        if not SPELLING.fullmatch(spelling):
            raise SourceError(f"line {no}: {spelling!r} is not a switch spelling (--name or --name=)")
        for what, sha in (("removed-in", removed), ("since", since)):
            if not SHA.fullmatch(sha):
                raise SourceError(f"line {no}: {what} {sha!r} is not a commit hash")
        if spelling in seen:
            raise SourceError(f"line {no}: {spelling} is already on line {seen[spelling]}")
        seen[spelling] = no
        rows.append((spelling, removed, since, reason.strip()))
    return rows


def render(rows: list[tuple[str, str, str, str]]) -> str:
    lines = ["// GENERATED by tools/gen_removed_flags.py from dp/removed_flags.txt -- do not edit.",
             "// Spellings of leveldp switches that were removed: the spelling, the commit that removed it and the",
             "// commit the refusal names (\"since\"). A spelling ending in '=' takes its value in the same token and is",
             "// matched as a prefix.",
             "#pragma once",
             "",
             "namespace dp {",
             "inline constexpr const char* const kRemovedFlags[][3] = {"]
    for spelling, removed, since, _ in rows:
        lines.append(f'    {{"{spelling}", "{removed}", "{since}"}},')
    lines += ["};", "}  // namespace dp", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        text = render(parse(SOURCE.read_text(encoding="utf-8")))
    except SourceError as e:
        print(f"{SOURCE.relative_to(ROOT).as_posix()}: {e}")
        return 2
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if a.check:
        if old != text:
            print("stale (run tools/gen_removed_flags.py): " + OUT.relative_to(ROOT).as_posix())
            return 1
        print("up to date")
        return 0
    if old != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote " + (OUT.relative_to(ROOT).as_posix() if old != text else "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
